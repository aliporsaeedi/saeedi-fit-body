function sfCatExistingIds_(sheet, idCol) {
  var out = {};
  try {
    var rd = sfRead_(sheet);
    var i = rd.idx[idCol];
    if (i === undefined) return out;
    rd.rows.forEach(function (r) { var v = normalize_(r[i]); if (v) out[v] = 1; });
  } catch (e) {}
  return out;
}

function sfCatNextId_(sheet, idCol, prefix, existing, used) {
  var n = 1, id = '';
  do { id = prefix + ('0000' + n).slice(-4); n++; } while (existing[id] || used[id]);
  used[id] = 1;
  return id;
}

